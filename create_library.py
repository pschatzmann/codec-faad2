#!/usr/bin/env python3
"""
Creates the Arduino library sources (src/) from the original faad2 project
located in original/faad2.

- copies the libfaad directory (*.c, *.h incl. codebook/) to src/libfaad
- copies include/neaacdec.h to src/
- generates src/faad.h from include/faad.h.in
- generates src/libfaad/faad_config.h (replaces the cmake / autoconf defines)
- generates library.properties, CMakeLists.txt (CMake / ESP-IDF) and idf_component.yml
- patches src/libfaad/common.h to include faad_config.h
- patches src/libfaad/codebook/hcb.h to include its tables relative to itself
- patches src/libfaad/fixed.h to use the ARM assembler only in ARM (not Thumb) mode

Usage: python3 create_library.py [--original original/faad2] [--dest .]
"""

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent

CONFIG_TEMPLATE = """\
/*
 * Configuration for the Arduino / CMake build of faad2.
 * Generated by create_library.py - do not edit, change the script instead.
 *
 * All settings can be overridden by compiler defines (e.g. -DFIXED_POINT).
 */
#pragma once

#ifndef PACKAGE_VERSION
#  define PACKAGE_VERSION "{version}"
#endif

#ifndef HAVE_INTTYPES_H
#  define HAVE_INTTYPES_H 1
#endif
#ifndef HAVE_STDINT_H
#  define HAVE_STDINT_H 1
#endif
#ifndef HAVE_STRING_H
#  define HAVE_STRING_H 1
#endif
#ifndef HAVE_MEMCPY
#  define HAVE_MEMCPY 1
#endif

/* Apply dynamic range control (enabled in the original cmake build) */
#if !defined(APPLY_DRC) && !defined(FAAD_NO_APPLY_DRC)
#  define APPLY_DRC 1
#endif

/*
 * Fixed point math is used on microcontrollers without hardware FPU:
 * ARM (e.g. Cortex-M0/M0+/M3, soft float ABI), Xtensa (e.g. ESP32-S2) and RISC-V
 * (e.g. ESP32-C3/C6/H2). Define FAAD_NO_FIXED_POINT to use floating point anyway.
 */
#if !defined(FIXED_POINT) && !defined(FAAD_NO_FIXED_POINT)
#  if (defined(__arm__) && (defined(__SOFTFP__) || !defined(__ARM_FP))) || \\
      (defined(__XTENSA__) && defined(__XTENSA_SOFT_FLOAT__)) || \\
      (defined(__riscv) && !defined(__riscv_flen))
#    define FIXED_POINT 1
#  endif
#endif

/*
 * Optional settings that can be activated with compiler defines:
 *  FIXED_POINT     - use fixed point math (recommended for MCUs without FPU)
 *  DRM_SUPPORT     - Digital Radio Mondiale support
 *  LC_ONLY_DECODER - pure AAC LC decoder (smallest)
 *  DISABLE_SBR     - disable SBR (HE-AAC) decoding
 *  SBR_LOW_POWER   - low power SBR decoding without PS
 */
"""

CMAKE_TEMPLATE = """\
# Generated by create_library.py
cmake_minimum_required(VERSION 3.16)

if(DEFINED ESP_PLATFORM)
  # ESP-IDF component
  idf_component_register(
    SRC_DIRS src/libfaad
    INCLUDE_DIRS src
  )
  target_compile_options(${{COMPONENT_LIB}} PRIVATE -Wno-error -Wno-unused-variable -Wno-unused-but-set-variable)

else()

project(faad2 VERSION {version} LANGUAGES C)

option(FAAD_FIXED_POINT "Use fixed point math" OFF)
option(FAAD_DRM "Digital Radio Mondiale support" OFF)
option(FAAD_LC_ONLY "Pure AAC LC decoder" OFF)
option(FAAD_DISABLE_SBR "Disable SBR (HE-AAC) decoding" OFF)
option(FAAD_SBR_LOW_POWER "Low power SBR decoding without PS" OFF)

file(GLOB FAAD_SOURCES CONFIGURE_DEPENDS ${{CMAKE_CURRENT_SOURCE_DIR}}/src/libfaad/*.c)

add_library(faad2 STATIC ${{FAAD_SOURCES}})
target_include_directories(faad2 PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}}/src)

if(FAAD_FIXED_POINT)
  target_compile_definitions(faad2 PUBLIC FIXED_POINT)
endif()
if(FAAD_DRM)
  target_compile_definitions(faad2 PUBLIC DRM_SUPPORT)
endif()
if(FAAD_LC_ONLY)
  target_compile_definitions(faad2 PUBLIC LC_ONLY_DECODER)
endif()
if(FAAD_DISABLE_SBR)
  target_compile_definitions(faad2 PUBLIC DISABLE_SBR)
endif()
if(FAAD_SBR_LOW_POWER)
  target_compile_definitions(faad2 PUBLIC SBR_LOW_POWER)
endif()

find_library(MATH_LIBRARY m)
if(MATH_LIBRARY)
  target_link_libraries(faad2 PUBLIC ${{MATH_LIBRARY}})
endif()

endif()
"""

IDF_COMPONENT = """\
version: "{version}"
description: FAAD2 AAC (LC, HE, MAIN, LTP) decoder
url: https://github.com/pschatzmann/codec-faad2
license: GPL-2.0-or-later
"""

LIBRARY_PROPERTIES = """\
name=codec-faad2
version={version}
author=M. Bakker, Nero AG and contributors
maintainer=Phil Schatzmann <phil.schatzmann@gmail.com>
sentence=FAAD2 AAC (LC, HE, MAIN, LTP) decoder
paragraph=Arduino port of the Freeware Advanced Audio (AAC) Decoder faad2
category=Signal Input/Output
url=https://github.com/pschatzmann/codec-faad2
architectures=*
includes=neaacdec.h
"""


def read_version(original: Path) -> str:
    with open(original / "properties.json") as f:
        return json.load(f)["PACKAGE_VERSION"]


def copy_sources(original: Path, src: Path):
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)
    # keep the libfaad directory structure, skip build files like faad2.pc.in
    shutil.copytree(original / "libfaad", src / "libfaad",
                    ignore=lambda d, names: [n for n in names
                                             if (Path(d) / n).is_file()
                                             and not n.endswith((".c", ".h"))])
    shutil.copy2(original / "include" / "neaacdec.h", src / "neaacdec.h")



def generate_faad_h(original: Path, src: Path, version: str):
    text = (original / "include" / "faad.h.in").read_text()
    text = text.replace("@VERSION@", version)
    # the pragma message would be printed for each compile
    text = re.sub(r'^#pragma message.*\n', "", text, flags=re.M)
    (src / "faad.h").write_text(text)


def patch_common_h(src: Path):
    path = src / "libfaad" / "common.h"
    text = path.read_text()
    old = '#ifdef HAVE_CONFIG_H\n#  include "../config.h"\n#endif\n'
    if old not in text:
        raise RuntimeError("common.h: config include not found - check patch")
    path.write_text(text.replace(old, '#include "faad_config.h"\n'))


def patch_hcb_h(src: Path):
    # upstream relies on libfaad being in the include path
    path = src / "libfaad" / "codebook" / "hcb.h"
    text, n = re.subn(r'#include "codebook/', '#include "', path.read_text())
    if n == 0:
        raise RuntimeError("hcb.h: codebook includes not found - check patch")
    path.write_text(text)


def patch_fixed_h(src: Path):
    # the inline assembler uses ARM mode syntax: Cortex-M (Thumb) must use the C code
    path = src / "libfaad" / "fixed.h"
    old = "#elif defined(__GNUC__) && defined (__arm__)\n"
    text = path.read_text()
    if old not in text:
        raise RuntimeError("fixed.h: ARM assembler condition not found - check patch")
    path.write_text(text.replace(old, "#elif defined(__GNUC__) && defined (__arm__) && !defined(__thumb__)\n"))


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--original", default=ROOT / "original" / "faad2", type=Path)
    parser.add_argument("--dest", default=ROOT, type=Path)
    args = parser.parse_args()

    original, dest = args.original.resolve(), args.dest.resolve()
    src = dest / "src"
    version = read_version(original)

    copy_sources(original, src)
    generate_faad_h(original, src, version)
    (src / "libfaad" / "faad_config.h").write_text(CONFIG_TEMPLATE.format(version=version))
    patch_common_h(src)
    patch_hcb_h(src)
    patch_fixed_h(src)

    for name in ("COPYING", "AUTHORS", "ChangeLog"):
        shutil.copy2(original / name, dest / name)
    (dest / "library.properties").write_text(LIBRARY_PROPERTIES.format(version=version))
    (dest / "CMakeLists.txt").write_text(CMAKE_TEMPLATE.format(version=version))
    (dest / "idf_component.yml").write_text(IDF_COMPONENT.format(version=version))

    count = sum(1 for f in src.rglob("*") if f.is_file())
    print(f"faad2 {version}: created {count} files in {src}")


if __name__ == "__main__":
    main()
